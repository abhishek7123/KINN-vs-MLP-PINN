def count_params(model: nn.Module) -> int:
    return sum(p.numel() for p in model.parameters() if p.requires_grad)


class MLP(nn.Module):
    _ACTS = {'tanh': nn.Tanh, 'silu': nn.SiLU}

    def __init__(self, input_dim, depth, width, act,
                 lb=None, ub=None):
        super().__init__()
        assert act in self._ACTS
        _lb = torch.zeros(input_dim) if lb is None else torch.tensor(lb, dtype=torch.float32)
        _ub = torch.ones(input_dim)  if ub is None else torch.tensor(ub, dtype=torch.float32)
        self.register_buffer('lb', _lb)
        self.register_buffer('ub', _ub)
        act_cls = self._ACTS[act]
        layers = [nn.Linear(input_dim, width), act_cls()]
        for _ in range(depth - 1):
            layers += [nn.Linear(width, width), act_cls()]
        layers.append(nn.Linear(width, 1))
        self.net = nn.Sequential(*layers)
        for m in self.net.modules():
            if isinstance(m, nn.Linear):
                nn.init.xavier_uniform_(m.weight)
                nn.init.zeros_(m.bias)

    def _norm(self, c):
        return 2.0 * (c - self.lb) / (self.ub - self.lb + 1e-12) - 1.0

    def forward(self, coords):
        return self.net(self._norm(coords))


class KINN(nn.Module):
    """
    Three mandatory KINN modifications (Wang et al. 2024):
    1. Input normalised to [-1,1]^d — B-splines only valid in grid_range.
    2. tanh after every hidden layer — prevents derivative collapse (Appendix C).
    3. Spline order k=3 fixed — accuracy plateaus beyond this (Fig 8b).
    """

    def __init__(self, input_dim, hidden_w, n_hidden, grid_size,
                 spline_order=KAN_SPLINE_K, lb=None, ub=None):
        super().__init__()
        if not KAN_AVAILABLE:
            raise RuntimeError('KAN not installed?')
        _lb = torch.zeros(input_dim) if lb is None else torch.tensor(lb, dtype=torch.float32)
        _ub = torch.ones(input_dim)  if ub is None else torch.tensor(ub, dtype=torch.float32)
        self.register_buffer('lb', _lb)
        self.register_buffer('ub', _ub)
        dims = [input_dim] + [hidden_w] * n_hidden + [1]
        self.kan_layers = nn.ModuleList([
            KANLinear(
                in_features=dims[i], out_features=dims[i+1],
                grid_size=grid_size, spline_order=spline_order,
                scale_noise=0.1, scale_base=1.0, scale_spline=1.0,
                enable_standalone_scale_spline=True,
                base_activation=nn.SiLU,
                grid_eps=0.02, grid_range=[-1.0, 1.0],
            )
            for i in range(len(dims) - 1)
        ])
        self._n_hidden = n_hidden

    def _norm(self, c):
        return 2.0 * (c - self.lb) / (self.ub - self.lb + 1e-12) - 1.0

    def forward(self, coords):
        h = self._norm(coords)
        for i, layer in enumerate(self.kan_layers):
            h = layer(h)
            if i < self._n_hidden:
                h = torch.tanh(h)
        return h

def _d1(u, c):
    return torch.autograd.grad(u, c, grad_outputs=torch.ones_like(u), create_graph=True)[0]


# 1D Convection
def u_convection(x, t, beta):
    return torch.sin(x - beta * t)

def res_convection(model, coords_f, beta):
    c = coords_f.detach().clone().requires_grad_(True)
    u = model(c)
    g = torch.autograd.grad(u, c, grad_outputs=torch.ones_like(u), create_graph=True)[0]
    u_x, u_t = g[:, 0:1], g[:, 1:2]
    return torch.mean((u_t + beta * u_x) ** 2)

def make_convection_data(seed=0):
    g   = torch.Generator(); g.manual_seed(seed)
    x_f = torch.rand(N_INT_CONV, 1, generator=g) * 2 * math.pi
    t_f = torch.rand(N_INT_CONV, 1, generator=g)
    x_ic = torch.linspace(0, 2 * math.pi, N_IC).reshape(-1, 1)
    t_bc = torch.rand(N_BC_EDGE, 1, generator=g)
    xv, tv = torch.linspace(0, 2*math.pi, N_VAL), torch.linspace(0, 1, N_VAL)
    X, T   = torch.meshgrid(xv, tv, indexing='ij')
    d = {
        'coords_f':    torch.cat([x_f, t_f], 1),
        'coords_ic':   torch.cat([x_ic, torch.zeros_like(x_ic)], 1),
        'u_ic':        torch.sin(x_ic),
        'coords_bc_L': torch.cat([torch.zeros(N_BC_EDGE, 1), t_bc], 1),
        'coords_bc_R': torch.cat([torch.full((N_BC_EDGE, 1), 2*math.pi), t_bc], 1),
        'x_val': X.reshape(-1, 1),
        't_val': T.reshape(-1, 1),
    }
    return {k: v.to(device) for k, v in d.items()}

def compute_losses_convection(model, data, beta, weights=None):
    w     = weights or {'pde': 1., 'ic': 1., 'bc': 1.}
    pde_l = res_convection(model, data['coords_f'], beta)
    ic_l  = torch.mean((model(data['coords_ic']) - data['u_ic']) ** 2)
    bc_l  = torch.mean((model(data['coords_bc_L']) - model(data['coords_bc_R'])) ** 2)
    return w['pde']*pde_l + w['ic']*ic_l + w['bc']*bc_l, pde_l, ic_l, bc_l

@torch.no_grad()
def eval_convection(model, data, beta):
    model.eval()
    coords_v = torch.cat([data['x_val'], data['t_val']], 1)
    u_pred   = model(coords_v)
    u_true   = u_convection(data['x_val'], data['t_val'], beta)
    err = (torch.sqrt(torch.mean((u_pred - u_true)**2)) /
           (torch.sqrt(torch.mean(u_true**2)) + 1e-12)).item()
    model.train(); return err


# 2D Helmholtz
def u_helmholtz(x, y, n):
    return torch.sin(n * math.pi * x) * torch.sin(n * math.pi * y)

def res_helmholtz(model, coords_f, n, k=1.0):
    c    = coords_f.detach().clone().requires_grad_(True)
    u    = model(c)
    x, y = c[:, 0:1], c[:, 1:2]
    g1   = torch.autograd.grad(u, c, grad_outputs=torch.ones_like(u), create_graph=True)[0]
    u_x, u_y = g1[:, 0:1], g1[:, 1:2]
    u_xx = _d1(u_x, c)[:, 0:1]
    u_yy = _d1(u_y, c)[:, 1:2]
    f    = (k**2 - 2*(n*math.pi)**2) * torch.sin(n*math.pi*x) * torch.sin(n*math.pi*y)
    return torch.mean((u_xx + u_yy + k**2 * u - f) ** 2)

def make_helmholtz_data(seed=0):
    g   = torch.Generator(); g.manual_seed(seed)
    x_f = torch.rand(N_INT_HELM, 1, generator=g) * 2 - 1
    y_f = torch.rand(N_INT_HELM, 1, generator=g) * 2 - 1
    e   = torch.rand(N_BC_EDGE, 1, generator=g) * 2 - 1
    o, mo = torch.ones(N_BC_EDGE, 1), -torch.ones(N_BC_EDGE, 1)
    xv, yv = torch.linspace(-1, 1, N_VAL), torch.linspace(-1, 1, N_VAL)
    X, Y   = torch.meshgrid(xv, yv, indexing='ij')
    d = {
        'coords_f':  torch.cat([x_f, y_f], 1),
        'coords_bc': torch.cat([
            torch.cat([e, o], 1), torch.cat([e, mo], 1),
            torch.cat([o, e], 1), torch.cat([mo, e], 1)
        ], 0),
        'x_val': X.reshape(-1, 1),
        'y_val': Y.reshape(-1, 1),
    }
    return {k: v.to(device) for k, v in d.items()}

def compute_losses_helmholtz(model, data, n, k=1.0, weights=None):
    w     = weights or {'pde': 1., 'bc': 1.}
    pde_l = res_helmholtz(model, data['coords_f'], n, k)
    bc_l  = torch.mean(model(data['coords_bc']) ** 2)
    ic_l  = torch.tensor(0., device=device)
    return w['pde']*pde_l + w['bc']*bc_l, pde_l, ic_l, bc_l

