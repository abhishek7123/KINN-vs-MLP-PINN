# 1D Multi-scale Poisson
def u_poisson_ms(x):
    return torch.sin(2 * math.pi * x) + 0.1 * torch.sin(50 * math.pi * x)

def res_poisson_ms(model, coords_f):
    c    = coords_f.detach().clone().requires_grad_(True)
    u    = model(c)
    u_x  = _d1(u, c)
    u_xx = _d1(u_x, c)
    f    = (4*math.pi**2 * torch.sin(2*math.pi*c) +
            250*math.pi**2 * torch.sin(50*math.pi*c))
    return torch.mean((-u_xx - f) ** 2)

def make_poisson_data(seed=0):
    g    = torch.Generator(); g.manual_seed(seed)
    x_f  = torch.rand(N_INT_POIS, 1, generator=g)
    x_bc = torch.tensor([[0.0], [1.0]])
    d = {
        'x_f':   x_f,
        'x_bc':  x_bc,
        'u_bc':  u_poisson_ms(x_bc),
        'x_val': torch.linspace(0, 1, N_VAL).reshape(-1, 1),
    }
    return {k: v.to(device) for k, v in d.items()}

def compute_losses_poisson(model, data, weights=None):
    w     = weights or {'pde': 1., 'bc': 1.}
    pde_l = res_poisson_ms(model, data['x_f'])
    bc_l  = torch.mean((model(data['x_bc']) - data['u_bc']) ** 2)
    ic_l  = torch.tensor(0., device=device)
    return w['pde']*pde_l + w['bc']*bc_l, pde_l, ic_l, bc_l

@torch.no_grad()
def eval_poisson(model, data):
    model.eval()
    err = (torch.sqrt(torch.mean((model(data['x_val']) - u_poisson_ms(data['x_val']))**2)) /
           (torch.sqrt(torch.mean(u_poisson_ms(data['x_val'])**2)) + 1e-12)).item()
    model.train(); return err

class AdaptiveWeighter:
    def __init__(self, alpha=0.9, update_every=100, clip=(0.01, 100.)):
        self.alpha = alpha
        self.every = update_every
        self.clip  = clip
        self.w     = {'pde': 1., 'ic': 1., 'bc': 1.}
        self._step = 0

    def _max_grad(self, loss, model):
        gs   = torch.autograd.grad(loss, model.parameters(), retain_graph=True, allow_unused=True)
        vals = [g.abs().max().item() for g in gs if g is not None]
        return max(vals) if vals else 1.

    def _mean_grad(self, loss, model):
        gs   = torch.autograd.grad(loss, model.parameters(), retain_graph=True, allow_unused=True)
        vals = [g.abs().mean().item() for g in gs if g is not None]
        return float(np.mean(vals)) if vals else 1.

    def step(self, losses_fn, model):
        self._step += 1

        if self._step % self.every != 0:
            return
        model.zero_grad()
        _, pde_l, ic_l, bc_l = losses_fn()
        ref = self._max_grad(pde_l, model)
        if ic_l.item() > 0.:
            raw = ref / (self._mean_grad(ic_l, model) + 1e-12)
            self.w['ic'] = self.alpha*self.w['ic'] + (1-self.alpha)*float(np.clip(raw, *self.clip))
        raw = ref / (self._mean_grad(bc_l, model) + 1e-12)
        self.w['bc'] = self.alpha*self.w['bc'] + (1-self.alpha)*float(np.clip(raw, *self.clip))
        model.zero_grad()

    def get(self):             return dict(self.w)
    def state_dict(self):      return {'w': self.w, 'step': self._step}
    def load_state_dict(self, d): self.w = d['w']; self._step = d['step']


def train(model, losses_fn, eval_fn, run_key, checkpoint,
          label='', use_adaptive=False,
          adam_epochs=ADAM_EPOCHS, lbfgs_outer=LBFGS_OUTER,
          patience=EARLY_PAT, seed=0):

    torch.manual_seed(seed)


    optimizer = optim.Adam(model.parameters(), lr=ADAM_LR)
    scheduler = optim.lr_scheduler.ExponentialLR(optimizer, gamma=0.9995)

    weighter    = AdaptiveWeighter() if use_adaptive else None
    best_l2     = float('inf')
    best_state  = None
    pat_ctr     = 0
    t0          = time.time()
    start_epoch = 0
    start_phase = 'adam'
    start_lbfgs = 0

    hist = {k: [] for k in
            ['epoch','total','pde','ic','bc','l2','w_pde','w_ic','w_bc','phase']}

    local_best = Path(f'/tmp/best_{run_key[:50]}.pt')

    #  Save optimizer and scheduler states
    def _pack_mid(epoch, phase, lbfgs_step=0):
        return {
            'model_state':      model.state_dict(),
            'optimizer_state':  optimizer.state_dict(),
            'scheduler_state':  scheduler.state_dict(),
            'best_model_state': best_state,
            'epoch':            epoch,
            'phase':            phase,
            'lbfgs_outer':      lbfgs_step,
            'best_l2':          best_l2,
            'patience_ctr':     pat_ctr,
            'history':          hist,
            'final_w':          weighter.get() if weighter else {'pde':1.,'ic':1.,'bc':1.},
            'weighter':         weighter.state_dict() if weighter else None,
        }

    # Restore states to prevent loss spikes
    mid = checkpoint.load_mid(run_key)
    if mid is not None:
        try:
            model.load_state_dict(mid['model_state'])
            if 'optimizer_state' in mid:
                optimizer.load_state_dict(mid['optimizer_state'])
            if 'scheduler_state' in mid:
                scheduler.load_state_dict(mid['scheduler_state'])

            best_l2     = mid['best_l2']
            best_state  = mid.get('best_model_state')
            pat_ctr     = mid.get('patience_ctr', 0)
            hist        = mid['history']
            start_phase = mid.get('phase', 'adam')
            start_epoch = mid.get('epoch', 0)
            start_lbfgs = mid.get('lbfgs_outer', 0)
            if weighter and mid.get('weighter'):
                weighter.load_state_dict(mid['weighter'])
        except Exception as e:
            print(f"Resume failed ({e}). Starting fresh.")
            mid = None

    def _log(epoch, total, pde_l, ic_l, bc_l, l2, ww, phase):
        for key, val in [
            ('epoch',epoch),('total',total.item()),('pde',pde_l.item()),
            ('ic',ic_l.item()),('bc',bc_l.item()),('l2',l2),
            ('w_pde',ww['pde']),('w_ic',ww['ic']),('w_bc',ww['bc']),
            ('phase',phase)
        ]:
            hist[key].append(val)

    already_done = start_epoch if start_phase == 'adam' else adam_epochs + start_lbfgs

    # Phase 1 — Adam
    adam_bar = tqdm(
        total=adam_epochs,
        desc=f'Adam  {label}',
        leave=True,

        dynamic_ncols=False,
        initial=start_epoch,
    )

    if start_phase == 'adam':
        model.train()
        for epoch in range(start_epoch + 1, adam_epochs + 1):
            optimizer.zero_grad()
            if weighter:
                weighter.step(lambda: losses_fn(None), model)
            w = weighter.get() if weighter else None
            total, pde_l, ic_l, bc_l = losses_fn(w)
            total.backward()

            #  Gradient Clipping Essential for high frequency / high beta stability
            torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)

            optimizer.step()
            scheduler.step()
            adam_bar.update(1)

            if epoch % LOG_EVERY == 0:
                l2 = eval_fn()
                ww = w or {'pde':1.,'ic':1.,'bc':1.}
                _log(epoch, total, pde_l, ic_l, bc_l, l2, ww, 'adam')
                adam_bar.set_postfix(L2=f'{l2:.3e}', PDE=f'{pde_l.item():.2e}')
                if l2 < best_l2:
                    best_l2    = l2
                    best_state = {k: v.cpu().clone() for k, v in model.state_dict().items()}
                    pat_ctr    = 0
                    torch.save(model.state_dict(), local_best)
                else:
                    pat_ctr += LOG_EVERY
                    if pat_ctr >= patience:
                        adam_bar.update(adam_epochs - epoch)
                        break

            if epoch % CKPT_EPOCHS == 0:
                checkpoint.save_mid(run_key, _pack_mid(epoch, 'adam'))

        if local_best.exists():

            model.load_state_dict(torch.load(local_best, map_location=device))
            local_best.unlink()

    adam_bar.close()

    # Phase 2 — LBFGS
    w_lb = weighter.get() if weighter else {'pde':1.,'ic':1.,'bc':1.}

    opt_lb = optim.LBFGS(
        model.parameters(), lr=1.0, max_iter=50, max_eval=65,
        history_size=50, tolerance_grad=1e-8, tolerance_change=1e-10,
        line_search_fn='strong_wolfe',
    )

    lbfgs_bar = tqdm(
        total=lbfgs_outer,
        desc=f'LBFGS {label}',
        leave=True,

        dynamic_ncols=False,
        initial=start_lbfgs,
    )

    model.train()
    for outer in range(lbfgs_outer):
        if outer < start_lbfgs:
            continue

        def closure():
            opt_lb.zero_grad()
            tot, _, _, _ = losses_fn(w_lb)
            tot.backward()
            return tot

        try:
            opt_lb.step(closure)
        except RuntimeError:
            lbfgs_bar.update(lbfgs_outer - outer)
            break

        lbfgs_bar.update(1)

        if outer % 10 == 0:
            tot, pde_l, ic_l, bc_l = losses_fn(w_lb)
            l2 = eval_fn()


            _log(adam_epochs + outer, tot, pde_l, ic_l, bc_l, l2, w_lb, 'lbfgs')

            lbfgs_bar.set_postfix(L2=f'{l2:.3e}', PDE=f'{pde_l.item():.2e}')
            if l2 < best_l2:
                best_l2    = l2
                best_state = {k: v.cpu().clone() for k, v in model.state_dict().items()}

        if outer % CKPT_LBFGS == 0 and outer > 0:
            checkpoint.save_mid(run_key, _pack_mid(adam_epochs + outer, 'lbfgs', outer))

    lbfgs_bar.close()
    checkpoint.clear_mid(run_key)

    return {
        'history':          hist,
        'best_l2':          best_l2,
        'best_model_state': best_state,
        'n_params':         count_params(model),
        'train_time':       time.time() - t0,
        'final_w':          w_lb,
    }

