    for n in tqdm(HELM_FREQS, desc='helmholtz n', colour='yellow'):
        for mtype in mtypes:
            for aw in [False, True]:
                for gs in ([10, 30] if mtype == 'KINN' else [None]):  # ← new loop
                    rk = make_run_key(pde='helm', model=mtype, n=n, aw=aw, gs=str(gs))
                    if checkpoint.is_done(rk):
                        continue

                    model = (
                        MLP(2, MLP_DEPTH, MLP_WIDTH, MLP_ACT, lb=LB, ub=UB)
                        if mtype == 'MLP'
                        else KINN(2, KAN_HIDDEN_W, KAN_N_HIDDEN, gs, lb=LB, ub=UB)
                    ).to(device)

                    lf = lambda w, m=model, d=data, n_=n: compute_losses_helmholtz(m, d, n_, K, w)
                    ef = lambda m=model, d=data, n_=n:    eval_helmholtz(m, d, n_)

