def plot_heatmap():
    df = _load('convection_heatmap.csv')
    if df is None:
        return

    pivot = df.pivot(index='beta', columns='grid_size', values='best_l2')
    pivot = pivot.sort_index(ascending=False)

    #load MLP baselines
    conv  = _load('convection_beta_sweep.csv')
    mlp_ref = {}
    if conv is not None:
        mlp_sub = conv[(conv['model'] == 'MLP') & (conv['adaptive'] == False)]
        for _, row in mlp_sub.iterrows():
            mlp_ref[int(row['beta'])] = row['best_l2']

    fig, ax = plt.subplots(figsize=(8, 5))

    log_data = np.log10(pivot.values.astype(float))
    vmin, vmax = log_data.min(), log_data.max()

    im = ax.imshow(log_data, cmap='RdYlGn_r', aspect='auto', vmin=vmin, vmax=vmax)

    for i in range(log_data.shape[0]):
        for j in range(log_data.shape[1]):
            val = pivot.values[i, j]
            text_color = 'white' if log_data[i, j] > (vmin + vmax) / 2 else 'black'
            ax.text(j, i, fmt(val), ha='center', va='center',
                    fontsize=9, color=text_color, fontweight='bold')

    ax.set_xticks(range(len(pivot.columns)))
    ax.set_xticklabels([f'gs={g}' for g in pivot.columns])
    ax.set_yticks(range(len(pivot.index)))
    ax.set_yticklabels([f'β={b}' for b in pivot.index])
    ax.set_xlabel('KAN Grid Size')
    ax.set_ylabel('Convection Speed β')
    ax.set_title('KINN: Relative L₂ Error — Grid Size × β\n(green = accurate, red = failure)')

    # MLP values below x-axis
    if mlp_ref:
        mlp_text = 'MLP baseline: ' + '   '.join(
            [f'β={b}: {fmt(v)}' for b, v in sorted(mlp_ref.items(), reverse=True)]
        )
        ax.set_xlabel(f'KAN Grid Size\n\n{mlp_text}', fontsize=9)

    cbar = plt.colorbar(im, ax=ax)
    cbar.set_label('log₁₀(L₂ error)')
    save(fig, 'fig2_heatmap.png')


# Loss decomposition at β=30


def plot_loss_decomp():
    df = _load('convection_loss_decomp.csv')
    if df is None:
        return

    df30 = df[df['beta'] == 30].copy()
    if df30.empty:
        print('  [missing] No β=30 data in loss_decomp CSV')
        return

    configs = [
        ('MLP',  False, COLORS['MLP_fixed'],    'MLP fixed'),
        ('MLP',  True,  COLORS['MLP_adaptive'], 'MLP adaptive'),
        ('KINN', False, COLORS['KINN_fixed'],    'KINN gs=20 fixed'),
        ('KINN', True,  COLORS['KINN_adaptive'], 'KINN gs=20 adaptive'),
    ]

    fig, axes = plt.subplots(1, 3, figsize=(13, 4), sharey=False)
    loss_keys = [('pde', 'PDE Residual'), ('ic', 'IC Loss'), ('bc', 'BC Loss')]

    for ax, (lkey, ltitle) in zip(axes, loss_keys):
        for mtype, aw, color, label in configs:
            sub = df30[(df30['model'] == mtype) & (df30['adaptive'] == aw)]
            if sub.empty:
                continue
            adam_sub  = sub[sub['phase'] == 'adam']
            lbfgs_sub = sub[sub['phase'] == 'lbfgs']
            if not adam_sub.empty:
                ax.semilogy(adam_sub['epoch'], adam_sub[lkey],
                            color=color, linewidth=1.5, label=label)
            if not lbfgs_sub.empty:
                ax.semilogy(lbfgs_sub['epoch'], lbfgs_sub[lkey],
                            color=color, linewidth=1.5, linestyle='--')
        ax.set_title(ltitle)
        ax.set_xlabel('Epoch')
        ax.axvline(x=8000, color='gray', linestyle=':', alpha=0.7)
        if ax == axes[0]:
            ax.set_ylabel('Loss value')

    axes[0].legend(fontsize=8, loc='upper right')
    fig.suptitle('Loss Decomposition at β=30  (solid=Adam, dashed=L-BFGS)', y=1.02)
    plt.tight_layout()
    save(fig, 'fig3_loss_decomp.png')


