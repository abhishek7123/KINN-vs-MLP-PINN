# Parameter efficiency (all β values)


def plot_param_efficiency():
    dfs = []

    for beta in [1, 10, 30, 50]:
        path = OUT / f'param_efficiency_beta{beta}.csv'
        if path.exists():
            temp = pd.read_csv(path)
            if not temp.empty and len(temp) > 2:
                temp['beta'] = beta
                dfs.append(temp)
                continue

        # Fallback
        conv = _load('convection_beta_sweep.csv')
        if conv is not None:
            sub = conv[conv['beta'] == beta][['model', 'n_params', 'best_l2', 'adaptive']].copy()
            sub = sub[sub['adaptive'] == False].copy()
            if not sub.empty:
                sub['depth']        = sub['model'].apply(lambda x: 4 if x == 'MLP' else 2)
                sub['width']        = sub['model'].apply(lambda x: 128 if x == 'MLP' else 5)
                sub['grid_size']    = sub['model'].apply(lambda x: None if x == 'MLP' else 10)
                sub['beta']         = beta
                sub['train_time_s'] = 0
                dfs.append(sub)

    if not dfs:
        print('  [missing] No param efficiency data found')
        return

    df = pd.concat(dfs, ignore_index=True)

    fig, axes = plt.subplots(1, 4, figsize=(16, 4.5), sharey=False)

    for ax, beta in zip(axes, [1, 10, 30, 50]):
        sub  = df[df['beta'] == beta]
        mlp  = sub[sub['model'] == 'MLP']
        kinn = sub[sub['model'] == 'KINN']

        if sub.empty:
            ax.text(0.5, 0.5, 'No data', ha='center', va='center',
                    transform=ax.transAxes)
        else:
            if not mlp.empty:
                ax.scatter(mlp['n_params'], mlp['best_l2'],
                           color=COLORS['MLP_fixed'], s=80, marker='o',
                           label='MLP', zorder=5, edgecolors='white', linewidths=0.5)
            if not kinn.empty:
                ax.scatter(kinn['n_params'], kinn['best_l2'],
                           color=COLORS['KINN_fixed'], s=80, marker='^',
                           label='KINN', zorder=5, edgecolors='white', linewidths=0.5)
            ax.set_xscale('log')
            ax.set_yscale('log')
            ax.legend(fontsize=8)

        ax.set_title(f'β={beta}')
        ax.set_xlabel('Parameters')
        ax.grid(True, alpha=0.3)
        if ax == axes[0]:
            ax.set_ylabel('Relative L₂ error')

    fig.suptitle('Parameter Efficiency: L₂ Error vs Model Size across β values',
                 fontsize=12, y=1.02)
    plt.tight_layout()
    save(fig, 'fig5_param_efficiency.png')


#Convection solution plots (exact vs MLP vs KINN)


def plot_solutions(beta=30):
    LB = [0., 0.]; UB = [2 * math.pi, 1.]
    xv = torch.linspace(0, 2 * math.pi, 256)
    tv = torch.linspace(0, 1, 256)
    X, T   = torch.meshgrid(xv, tv, indexing='ij')
    coords = torch.cat([X.reshape(-1,1), T.reshape(-1,1)], 1).to(device)
    u_exact = torch.sin(coords[:,0:1] - beta * coords[:,1:2]).cpu().numpy().reshape(256, 256)

    fig, axes = plt.subplots(1, 3, figsize=(13, 4))
    vmin, vmax = -1.0, 1.0

    im = axes[0].imshow(u_exact, extent=[0,1,0,2*math.pi],
                        aspect='auto', origin='lower', cmap='RdBu_r',
                        vmin=vmin, vmax=vmax)
    axes[0].set_title('Exact solution')
    axes[0].set_xlabel('t'); axes[0].set_ylabel('x')
    plt.colorbar(im, ax=axes[0])

    # MLP
    mlp_key  = f'aw=False_beta={beta}_model=MLP_pde=conv'
    mlp_path = OUT / f'weights_{mlp_key}.pt'
    if mlp_path.exists():
        mlp = MLP(2, MLP_DEPTH, MLP_WIDTH, MLP_ACT, lb=LB, ub=UB).to(device)
        mlp.load_state_dict(torch.load(mlp_path, map_location=device))
        mlp.eval()
        with torch.no_grad():
            u_mlp = mlp(coords).cpu().numpy().reshape(256, 256)
        l2  = np.sqrt(np.mean((u_mlp-u_exact)**2)) / np.sqrt(np.mean(u_exact**2))
        im2 = axes[1].imshow(u_mlp, extent=[0,1,0,2*math.pi],
                             aspect='auto', origin='lower', cmap='RdBu_r',
                             vmin=vmin, vmax=vmax)
        axes[1].set_title(f'MLP-PINN  (L₂={fmt(l2)})')
        axes[1].set_xlabel('t'); axes[1].set_ylabel('x')
        plt.colorbar(im2, ax=axes[1])
    else:
        axes[1].text(0.5, 0.5, 'weights not found', ha='center', va='center',
                     transform=axes[1].transAxes, fontsize=9)

    # KINN gs=10
    kinn_key  = f'aw = False_beta = {beta}_gs = 10_model= KINN_pde = conv'
    kinn_path = OUT / f'weights_{kinn_key}.pt'
    if kinn_path.exists():
        kan = KINN(2, KAN_HIDDEN_W, KAN_N_HIDDEN, 10, lb=LB, ub=UB).to(device)
        kan.load_state_dict(torch.load(kinn_path, map_location=device))
        kan.eval()
        with torch.no_grad():
            u_kinn = kan(coords).cpu().numpy().reshape(256, 256)
        l2   = np.sqrt(np.mean((u_kinn-u_exact)**2)) / np.sqrt(np.mean(u_exact**2))
        im3  = axes[2].imshow(u_kinn, extent=[0,1,0,2*math.pi],
                              aspect='auto', origin='lower', cmap='RdBu_r',
                              vmin=vmin, vmax=vmax)
        axes[2].set_title(f'KINN gs=10  (L₂={fmt(l2)})')
        axes[2].set_xlabel('t'); axes[2].set_ylabel('x')
        plt.colorbar(im3, ax=axes[2])
    else:
        axes[2].text(0.5, 0.5, 'weights not found', ha='center', va='center',
                     transform=axes[2].transAxes, fontsize=9)

    fig.suptitle(f'Convection solution comparison  β={beta}', y=1.02)
    plt.tight_layout()
    save(fig, f'fig6_solution_beta{beta}.png')

# Summary table


def plot_summary_table():
    conv = _load('convection_beta_sweep.csv')
    if conv is None:
        return

    rows = []
    for beta in [1, 10, 30, 50]:
        mlp_f = conv[(conv['model']=='MLP') & (~conv['adaptive']) & (conv['beta']==beta)]['best_l2'].values
        mlp_a = conv[(conv['model']=='MLP') & (conv['adaptive'])  & (conv['beta']==beta)]['best_l2'].values
        kinn  = conv[(conv['model']=='KINN') & (~conv['adaptive']) & (conv['beta']==beta)]['best_l2']
        rows.append({
            'β':           beta,
            'MLP fixed':   mlp_f[0] if len(mlp_f) > 0 else np.nan,
            'MLP adaptive':mlp_a[0] if len(mlp_a) > 0 else np.nan,
            'KINN best':   kinn.min() if not kinn.empty else np.nan,
        })

    df_s = pd.DataFrame(rows)
    fig, ax = plt.subplots(figsize=(9, 3))
    ax.axis('off')

    table_data = []
    for _, row in df_s.iterrows():
        table_data.append([
            f"β={int(row['β'])}",
            fmt(row['MLP fixed']),
            fmt(row['MLP adaptive']),
            fmt(row['KINN best']),
        ])

    tbl = ax.table(
        cellText=table_data,
        colLabels=['β', 'MLP (fixed)', 'MLP (adaptive)', 'KINN (best grid)'],
        cellLoc='center', loc='center',
    )
    tbl.auto_set_font_size(False)
    tbl.set_fontsize(11)
    tbl.scale(1.2, 2.0)

    for (row, col), cell in tbl.get_celld().items():
        if row == 0:
            cell.set_facecolor('#37474F')
            cell.set_text_props(color='white', fontweight='bold')
        elif col > 0:
            try:
                val = float(cell.get_text().get_text())
                if val > 0.1:
                    cell.set_facecolor('#FFCDD2')
                elif val < 0.01:
                    cell.set_facecolor('#C8E6C9')
                else:
                    cell.set_facecolor('#FFF9C4')
            except ValueError:
                pass

    ax.set_title('Convection: Relative L₂ Error  (green < 0.01 | yellow 0.01–0.1 | red > 0.1)',
                 pad=20, fontsize=11)
    save(fig, 'fig7_summary_table.png')



